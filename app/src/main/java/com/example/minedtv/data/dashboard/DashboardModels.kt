package com.example.minedtv.data.dashboard

import com.example.minedtv.data.Clip
import java.time.LocalDate

/** Where a clip's MinedTv views come from. Colours are fixed per source (see DashboardColors). */
enum class TrafficSource(val label: String) { Feed("Home feed"), Search("Search"), Profile("Profile"), SharedLink("Shared links") }

/** A clip is "published" once it's posted to the MinedTv feed. */
data class Publication(val publishedOn: LocalDate)

data class DailyStat(val day: LocalDate, val views: Long, val likes: Long, val comments: Long, val shares: Long)

enum class Metric(val label: String) { Views("Views"), Likes("Likes"), Comments("Comments"), Shares("Shares") }

fun DailyStat.value(m: Metric): Long = when (m) {
    Metric.Views -> views
    Metric.Likes -> likes
    Metric.Comments -> comments
    Metric.Shares -> shares
}

data class DashboardClip(
    val clip: Clip,
    /** Null while it's a draft. */
    val publication: Publication?,
    /** Daily MinedTv stats, oldest first (empty for drafts). */
    val history: List<DailyStat>,
    /** Share of this clip's views per traffic source (sums to 1). */
    val trafficShare: Map<TrafficSource, Float> = emptyMap(),
    /** Draft that was recorded on this phone. */
    val isLocalRecording: Boolean = false,
    /** All-time totals when there's no daily history (live backend data). */
    val totals: Map<Metric, Long> = emptyMap(),
    /** Backend "ready" bucket: queued to post to YouTube. */
    val isReadyToPost: Boolean = false
) {
    val isPublished get() = publication != null
    fun total(m: Metric, days: Int) = if (history.isEmpty()) totals[m] ?: 0L else history.takeLast(days).sumOf { it.value(m) }
}

sealed interface ViralityState {
    data object None : ViralityState
    data object Processing : ViralityState
    data class Ready(val report: ViralityReport) : ViralityState
    data class Failed(val message: String) : ViralityState
}

// ---- Virality engine (mirrors the backend's AudienceSimulation) ----

enum class ViralityPlatform(val label: String, val apiName: String) {
    General("MinedTv", "general"), TikTok("TikTok", "tiktok"), Instagram("Reels", "instagram"), YouTube("YouTube", "youtube")
}

enum class Verdict(val label: String) { Weak("Weak"), Mixed("Mixed"), Promising("Promising"), Strong("Strong") }

enum class AudienceLayer(val label: String) { Target("Core fans"), Adjacent("Adjacent viewers"), Outsider("Outsiders") }

enum class AudienceAction(val label: String) { Like("Like"), Comment("Comment"), Save("Save"), Share("Share"), Skip("Skip") }

data class LayerResult(
    val layer: AudienceLayer,
    val personaCount: Int,
    val score: Float,        // 0-100
    val threshold: Float,    // 0-100
    val exposed: Boolean,    // previous layer cleared, so this layer saw it
    val cleared: Boolean     // scored above threshold, so the cascade continues
)

data class PersonaReview(
    val name: String,
    val layer: AudienceLayer,
    val profile: String,
    val hookScore: Int,
    val primaryAction: AudienceAction,
    val reaction: String,
    val friction: String
)

data class ViralityReport(
    val platform: ViralityPlatform,
    val score: Float,
    val verdict: Verdict,
    val inferredAudience: String,
    val cascadeSummary: String,
    /** Percentages 0-100. */
    val watchRate: Float,
    val completionRate: Float,
    val likeRate: Float,
    val commentRate: Float,
    val shareRate: Float,
    val layers: List<LayerResult>,
    val personas: List<PersonaReview>,
    val strengths: List<String>,
    val risks: List<String>,
    val changes: List<String>,
    val disclaimer: String = "Synthetic persona feedback is a creative testing aid, not real analytics or a performance guarantee.",
    /**
     * Scores from independent audience panels (the first is [score]). Each panel is freshly
     * generated by the AI, so the same clip can land several points apart; we show the spread.
     */
    val samples: List<Float> = listOf(score),
    /** More panels are still running for the range. */
    val rangePending: Boolean = false
)

/** The headline: the middle score of all panels (just [ViralityReport.score] with one panel). */
val ViralityReport.median: Float get() = samples.sorted().let { it[(it.size - 1) / 2] }
val ViralityReport.low: Float get() = samples.min()
val ViralityReport.high: Float get() = samples.max()
val ViralityReport.hasRange: Boolean get() = samples.size > 1
/** Verdict for the median, using the backend's cut-offs. */
val ViralityReport.medianVerdict: Verdict get() = verdictFor(median)
/** Panels disagree on the verdict (the range crosses a cut-off). */
val ViralityReport.borderline: Boolean get() = verdictFor(low) != verdictFor(high)

fun verdictFor(score: Float): Verdict = when {
    score >= 75 -> Verdict.Strong
    score >= 55 -> Verdict.Promising
    score >= 35 -> Verdict.Mixed
    else -> Verdict.Weak
}
